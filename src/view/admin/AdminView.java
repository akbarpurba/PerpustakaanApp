    private void btn_addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_addActionPerformed
        // TODO add your handling code here:
        AdminController adminController = new AdminController();
        String usernameValue
                = username.getText();
        String nameValue
                = name.getText();

        String passwordValue
                = String.valueOf(
                        password.getPassword()
                );
        String hashedPassword =
            BCrypt.hashpw(
                    passwordValue,
                    BCrypt.gensalt()
            );

        String jabatanValue
                = jabatan.getSelectedItem()
                        .toString();

        if (usernameValue.isEmpty()
                || nameValue.isEmpty()
                || passwordValue.isEmpty()) {

            MessageUtil.warning(
                    this,
                    "Lengkapi semua data"
            );

            return;
        }

        Admin admin = new Admin();
        
        admin.setUsername(
                usernameValue
        );

        admin.setName(
                nameValue
        );

        admin.setPassword(
                hashedPassword
        );
        
        admin.setJabatan(
                jabatanValue
        );

      
        
        boolean result
                = adminController.tambahAdmin(
                        admin
                );

        if (result) {

            MessageUtil.success(
                    this,
                    "Admin berhasil ditambahkan"
            );

            tampilDataAdmin();

            resetForm();

        } else {

            MessageUtil.error(
                    this,
                    "Gagal menambahkan admin"
            );
        }

    }//GEN-LAST:event_btn_addActionPerformed

    private void btn_updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_updateActionPerformed
        // TODO add your handling code here:
        if (id_admin.getText().isEmpty()) {

            MessageUtil.warning(
                    this,
                    "Pilih data admin terlebih dahulu"
            );

            return;
        }
        AdminController adminController
                = new AdminController();

        Admin admin = new Admin();

        admin.setIdAdmin(
                Integer.parseInt(
                        id_admin.getText()
                )
        );
        admin.setUserId(selectedUserId);
        admin.setUsername(
                username.getText()
        );

        admin.setName(
                name.getText()
        );

        String hashedPassword =
            BCrypt.hashpw(
                    String.valueOf(
                        password.getPassword()
                ),
                    BCrypt.gensalt()
            );
        admin.setPassword(
                hashedPassword
        );

        admin.setJabatan(
                jabatan.getSelectedItem()
                        .toString()
        );
        
        

        boolean result
                = adminController.updateAdmin(
                        admin
                );

        if (result) {

            MessageUtil.success(
                    this,
                    "Data admin berhasil diupdate"
            );

            tampilDataAdmin();

            resetForm();

        } else {

            MessageUtil.error(
                    this,
                    "Gagal update admin"
            );
        }
    }//GEN-LAST:event_btn_updateActionPerformed

    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
        // TODO add your handling code here:
        if (id_admin.getText().isEmpty()) {

            MessageUtil.warning(
                    this,
                    "Pilih data admin terlebih dahulu"
            );

            return;
        }

        int confirm
                = MessageUtil.confirm(
                        this,
                        "Hapus admin ini?"
                );

        if (confirm
                != JOptionPane.YES_OPTION) {

            return;
        }

        int userId
                = selectedUserId;

        AdminController adminController
                = new AdminController();

        boolean result
                = adminController.deleteAdmin(
                        userId
                );

        if (result) {

            MessageUtil.success(
                    this,
                    "Admin berhasil dihapus"
            );

            tampilDataAdmin();

            resetForm();

        } else {

            MessageUtil.error(
                    this,
                    "Gagal menghapus admin"
            );
        }
    }//GEN-LAST:event_btn_deleteActionPerformed

    private void table_adminMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_table_adminMouseClicked
        // TODO add your handling code here:
         int row
            = table_admin.getSelectedRow();

    if (row < 0) {

        return;
    }

    int idAdmin
            = Integer.parseInt(
                    table_admin.getValueAt(
                            row,
                            0
                    ).toString()
            );
     
    AdminController adminController
            = new AdminController();

    Admin admin
            = adminController.getAdminById(
                    idAdmin
            );
    
    if (admin != null) {

        selectedUserId
                = admin.getUserId();
       
        id_admin.setText(
                String.valueOf(
                        admin.getIdAdmin()
                )
        );
        username.setText(
                admin.getUsername()
        );

        name.setText(
                admin.getName()
        );

        jabatan.setSelectedItem(
                admin.getJabatan()
        );
    }
    }//GEN-LAST:event_table_adminMouseClicked

