    private void tampilDataAdmin() {

        DefaultTableModel model
                = (DefaultTableModel) table_admin.getModel();

        model.setRowCount(0);

        AdminController adminController
                = new AdminController();

        ArrayList<Admin> list
                = adminController.getAllAdmin();

        for (Admin admin : list) {

            Object[] row = {
                admin.getIdAdmin(),
                admin.getUsername(),
                admin.getName(),
                admin.getJabatan()

            };

            model.addRow(row);
        }
    }

